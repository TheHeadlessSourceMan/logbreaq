import type { FileSystem } from '../fs/fileSystem';
import { joinPath } from '../fs/paths';
import { graphId, type ScannedGraph } from '../indexing/graphScanner';
import type { LocationIndex } from '../indexing/pageLocationIndex';
import type { Logger } from '../logging/logger';
import type {
  AssetAction,
  Conflict,
  FileOperation,
  GraphRef,
  LinkRewrite,
  MigrationRequest,
  MigrationSnapshot,
  ResolvedConflict,
} from '../model/types';
import type { LinkRenderer } from '../rendering/linkRenderer';
import type { ConflictResolver } from '../conflicts/conflictResolver';

export interface MigrationDependencies {
  readonly fs: FileSystem;
  readonly logger: Logger;
  readonly linkRenderer: LinkRenderer;
  readonly conflictResolver: ConflictResolver;
  readonly now: () => number;
}

export interface AffectedPage {
  readonly graphId: string;
  readonly key: string;
}

/** Per-run working state. Created fresh for every migration; never shared. */
export interface MigrationState {
  readonly sourceId: string;
  readonly targetId: string;
  /** Every graph scanned during this run, by graph id. */
  readonly graphs: Map<string, ScannedGraph>;
  targetGraphCreated: boolean;
  /** Keys (in the source graph) of the pages the user selected. */
  readonly selectedKeys: Set<string>;
  conflicts: Conflict[];
  readonly resolvedConflicts: ResolvedConflict[];
  readonly skippedPages: Set<string>;
  /** Source page key -> new page name. */
  readonly renames: Map<string, string>;
  /** Selected keys minus skipped pages. */
  readonly movingKeys: Set<string>;
  locationIndex: LocationIndex | undefined;
  /** Index files that already existed when the run started. */
  readonly existingIndexFiles: string[];
  affectedPages: AffectedPage[];
  assetActions: AssetAction[];
  /** Lower-cased asset names that were already missing before the migration. */
  readonly missingAssets: Set<string>;
  snapshot: MigrationSnapshot | undefined;
  /** Path -> sha256 of the content this run last observed or wrote. */
  readonly fileHashes: Map<string, string>;
  /** Path -> sha256 of files created by this run. */
  readonly createdFiles: Map<string, string>;
  /** Source page key -> path of the page in the target graph. */
  readonly movedPageTargets: Map<string, string>;
  /** Page file path -> link texts generated by this run. */
  readonly generatedLinks: Map<string, Set<string>>;
  /** Source files deleted only after integrity validation succeeds. */
  readonly pendingRemovals: string[];
  readonly pagesMoved: string[];
  readonly filesMoved: FileOperation[];
  readonly filesCopied: FileOperation[];
  readonly linksRewritten: LinkRewrite[];
  readonly warnings: string[];
  readonly rollbackLog: string[];
}

export interface MigrationContext {
  readonly request: MigrationRequest;
  readonly deps: MigrationDependencies;
  readonly state: MigrationState;
}

export function createInitialState(request: MigrationRequest): MigrationState {
  return {
    sourceId: graphId(request.sourceGraph.path),
    targetId: graphId(request.targetGraph.path),
    graphs: new Map(),
    targetGraphCreated: false,
    selectedKeys: new Set(),
    conflicts: [],
    resolvedConflicts: [],
    skippedPages: new Set(),
    renames: new Map(),
    movingKeys: new Set(),
    locationIndex: undefined,
    existingIndexFiles: [],
    affectedPages: [],
    assetActions: [],
    missingAssets: new Set(),
    snapshot: undefined,
    fileHashes: new Map(),
    createdFiles: new Map(),
    movedPageTargets: new Map(),
    generatedLinks: new Map(),
    pendingRemovals: [],
    pagesMoved: [],
    filesMoved: [],
    filesCopied: [],
    linksRewritten: [],
    warnings: [],
    rollbackLog: [],
  };
}

/** Expected stop: nothing (further) should be changed and the user should be told why. */
export class MigrationAbortedError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'MigrationAbortedError';
  }
}

export class IntegrityError extends Error {
  constructor(readonly problems: readonly string[]) {
    super(`Integrity check failed:\n- ${problems.join('\n- ')}`);
    this.name = 'IntegrityError';
  }
}

function requireGraph(ctx: MigrationContext, id: string, label: string): ScannedGraph {
  const graph = ctx.state.graphs.get(id);
  if (graph === undefined) {
    throw new Error(`${label} graph has not been scanned yet.`);
  }
  return graph;
}

export function sourceGraph(ctx: MigrationContext): ScannedGraph {
  return requireGraph(ctx, ctx.state.sourceId, 'Source');
}

export function targetGraph(ctx: MigrationContext): ScannedGraph {
  return requireGraph(ctx, ctx.state.targetId, 'Target');
}

export function graphDir(ctx: MigrationContext, graph: GraphRef, folder: 'pagesDir' | 'journalsDir' | 'assetsDir'): string {
  return joinPath(graph.path, ctx.request.layout[folder]);
}

export function finalPageName(ctx: MigrationContext, key: string): string {
  const renamed = ctx.state.renames.get(key);
  if (renamed !== undefined) {
    return renamed;
  }
  const page = sourceGraph(ctx).pages.get(key);
  if (page === undefined) {
    throw new Error(`Unknown source page key: ${key}`);
  }
  return page.name;
}

export function sortedMovingKeys(ctx: MigrationContext): string[] {
  return [...ctx.state.movingKeys].sort();
}

export function isMovingPage(ctx: MigrationContext, graphIdValue: string, key: string): boolean {
  return graphIdValue === ctx.state.sourceId && ctx.state.movingKeys.has(key);
}

export function describeError(error: unknown): string {
  return error instanceof Error ? `${error.name}: ${error.message}` : String(error);
}
